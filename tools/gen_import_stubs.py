#!/usr/bin/env python3
"""Generate logging stubs for every kernel/XAM import the runtime doesn't implement yet.

Usage: gen_import_stubs.py <generated/ppc/ppc_recomp_shared.h> <runtime/src/kernel> <out.cpp>

An import counts as implemented when some file under runtime/src/kernel contains
GUEST_IMPORT(Name). Everything else gets a stub that logs the call and returns 0.
"""
import os, re, sys

shared, kernel_dir, out = sys.argv[1:4]
imports = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", open(shared).read())))
implemented = set()
for root, _, files in os.walk(kernel_dir):
    for fn in files:
        if fn.endswith((".cpp", ".h")):
            implemented |= set(re.findall(r"GUEST_IMPORT\((\w+)\)", open(os.path.join(root, fn), encoding="utf-8").read()))

missing = [n for n in imports if n not in implemented]
lines = ["// AUTO-GENERATED by tools/gen_import_stubs.py - do not edit.",
         f"// {len(imports)} imports, {len(imports) - len(missing)} implemented, {len(missing)} stubbed.",
         '#include "kernel/kernel.h"', ""]
for n in missing:
    lines.append(f'GUEST_IMPORT({n}) {{ wet::StubCall("{n}", ctx); }}')
lines.append("")
lines.append("namespace wet { const char* const kStubbedImports[] = {")
lines += [f'    "{n}",' for n in missing]
lines.append("    nullptr }; }")
new = "\n".join(lines) + "\n"
if not os.path.exists(out) or open(out).read() != new:
    open(out, "w").write(new)
print(f"[stubs] {len(imports)} imports: {len(imports) - len(missing)} implemented, {len(missing)} stubbed")
